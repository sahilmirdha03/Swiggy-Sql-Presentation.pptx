    deliverypartners.name,
    COUNT(orderdelivery.order_id) No_of_deliveries
FROM
    deliverypartners
        JOIN
    orderdelivery USING (partner_id)
GROUP BY 1
HAVING COUNT(order_delivery_id) > 1;

#Q11.Find the customers who have placed orders on exactly three different days.
SELECT 
    customers.name,
    COUNT(DISTINCT DATE(orders.order_date)) AS count
FROM
    customers
        JOIN
    orders USING (customer_id)
GROUP BY 1
HAVING count = 3;

