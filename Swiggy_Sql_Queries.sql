#Q1.Display all customers who live in 'Delhi'.
SELECT 
    name, city
FROM
    customers
WHERE
    city = 'delhi';
    
#Q2.Find the average rating of all restaurants in 'Mumbai'.    
SELECT 
    city, restaurant_id, name, AVG(rating)
FROM
    restaurants
WHERE
    city = 'mumbai'
GROUP BY city , restaurant_id , name;

#Q3.List all customers who have placed at least one order.
SELECT 
    customers.name, COUNT(orders.order_id) No_Of_Orders
FROM
    customers
        JOIN
    orders USING (customer_id)
GROUP BY 1
HAVING COUNT(orders.order_id) > 1;

#Q4.Display the total number of orders placed by each customer.
SELECT 
    customers.name, COUNT(orders.order_id)
FROM
    customers
        JOIN
    orders USING (customer_id)
GROUP BY 1;

#Q5.Find the total revenue generated by each restaurant.
SELECT 
    restaurants.name, SUM(orders.total_amount) total_revenue
FROM
    restaurants
        JOIN
    orders USING (restaurant_id)
GROUP BY 1;

#Q6.Find the top 5 restaurants with the highest average rating.
SELECT 
    name, AVG(rating) top_5_avg_ratings
FROM
    restaurants
GROUP BY 1
ORDER BY AVG(rating) DESC
LIMIT 5;

#Q7.Display all customers who have never placed an order.
SELECT 
    name
FROM
    customers
WHERE
    customer_id NOT IN (SELECT 
            customer_id
        FROM
            orders);

#Q8.Find the number of orders placed by each customer in 'Mumbai'.
SELECT 
    customers.name,
    COUNT(orders.order_id) No_of_orders,
    customers.city
FROM
    customers
        JOIN
    orders USING (customer_id)
WHERE
    city = 'mumbai'
GROUP BY customers.name , customers.city;

#Q9.Display all orders placed in the last 30 days.
SELECT 
    order_id, DATE(order_date)
FROM
    orders
WHERE
    order_date >= DATE_SUB((SELECT 
                MAX(order_date)
            FROM
                orders),
        INTERVAL 30 DAY);

#Q10.List all delivery partners who have completed more than 1 delivery
