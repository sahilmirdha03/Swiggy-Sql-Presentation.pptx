#Q13.Identify customers who have the same city and have placed orders at the same restaurants, but on different dates
with cte as(select customers.name ,customers.city,customers.customer_id,orders.restaurant_id,date(orders.order_date) order_date
from customers join orders
using(customer_id))

select * 
from cte as a join cte as b
on a.city=b.city
and a.restaurant_id=b.restaurant_id
and a.order_date<>b.order_date
